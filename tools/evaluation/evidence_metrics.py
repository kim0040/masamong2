"""Small, retrieval-only evidence gold validator and metric calculator.

The evaluator deliberately works with immutable *observation IDs*.  A result
from a retriever may have come from several overlapping windows, so repeated
observation IDs are collapsed before applying ``k``.  Window IDs, speaker
names, text equality, and an answer generated by an LLM are not evidence
signals in this module.

Gold input is a JSON mapping (or a :class:`GoldSet`) with this shape::

    {
      "schema_version": 1,
      "dataset_id": "...",
      "gold_kind": "synthetic" | "human_reviewed",
      "review_status": "unreviewed" | "reviewed",
      "reviewer": null | "reviewer-id",
      "observations": [
        {
          "observation_id": "obs-1",
          "source_provenance_id": "immutable-source-1",
          "source_channel_id": "discord:channel-a",
          "text": "..."
        }
      ],
      "questions": [
        {
          "question_id": "q-1",
          "split": "dev",
          "question_split_group": "episode-1",
          "episode_group": "episode-1",
          "allowed_source_channel_ids": ["discord:channel-a"],
          "required_evidence_groups": [
            {"group_id": "fact-a", "alternatives": ["obs-1"]}
          ],
          "forbidden_observation_ids": [],
          "abstain_expected": false,
          "review_status": "unreviewed",
          "reviewer": null
        }
      ]
    }

``required_evidence_groups`` is an AND of groups; ``alternatives`` is an OR
inside one group.  Thus a multi-evidence question is complete only when every
group has at least one independently retrieved observation.

This is intentionally not an answer judge.  It reports retrieval evidence
coverage and scope violations only.  In particular, it does not claim that a
retrieved observation supports a generated answer or correctly attributes a
fact to a person.
"""

from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path
from types import MappingProxyType
from typing import Any, Iterable, Mapping, Sequence


class GoldContractError(ValueError):
    """The gold mapping violates the evidence evaluation contract."""


class DuplicateIdentifierError(GoldContractError):
    """An immutable observation or provenance identifier is repeated."""


class UnknownObservationReferenceError(GoldContractError):
    """A gold or retrieved reference does not identify a known observation."""


class SplitLeakageError(GoldContractError):
    """A question/episode group crosses evaluation splits."""


class EmptyPositiveGoldError(GoldContractError):
    """A non-abstaining question has no positive evidence."""


def _non_empty_string(value: Any, field: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise GoldContractError(f"{field} must be a non-empty string")
    return value


def _optional_string(value: Any, field: str) -> str | None:
    if value is None:
        return None
    return _non_empty_string(value, field)


def _string_list(value: Any, field: str, *, allow_empty: bool = True) -> tuple[str, ...]:
    if isinstance(value, (str, bytes, bytearray)) or not isinstance(value, Sequence):
        raise GoldContractError(f"{field} must be a list of strings")
    result: list[str] = []
    for index, item in enumerate(value):
        result.append(_non_empty_string(item, f"{field}[{index}]") )
    if not allow_empty and not result:
        raise GoldContractError(f"{field} must not be empty")
    if len(result) != len(set(result)):
        raise DuplicateIdentifierError(f"{field} contains duplicate identifiers")
    return tuple(result)


def _mapping(value: Any, field: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise GoldContractError(f"{field} must be an object")
    return value


@dataclass(frozen=True, slots=True)
class Observation:
    """An immutable source observation addressable by the evaluator.

    ``text`` is retained so a fixture can demonstrate identical text across
    channels, but text is never used to satisfy a gold group.  The stable
    identity is ``observation_id`` plus its unique source provenance ID.
    """

    observation_id: str
    source_provenance_id: str
    source_channel_id: str
    text: str
    source_kind: str | None = None
    source_room_id: str | None = None
    source_file_id: str | None = None
    source_ordinal: int | None = None

    @classmethod
    def from_mapping(cls, raw: Mapping[str, Any], index: int = 0) -> "Observation":
        raw = _mapping(raw, f"observations[{index}]")
        observation_id = _non_empty_string(raw.get("observation_id"), f"observations[{index}].observation_id")

        provenance_value = raw.get("source_provenance_id")
        immutable_value = raw.get("immutable_source_provenance_id")
        if provenance_value is None:
            provenance_value = immutable_value
        elif immutable_value is not None and provenance_value != immutable_value:
            raise GoldContractError(
                f"observations[{index}] has conflicting source provenance IDs"
            )
        source_provenance_id = _non_empty_string(
            provenance_value, f"observations[{index}].source_provenance_id"
        )

        channel_value = raw.get("source_channel_id")
        if channel_value is None:
            channel_value = raw.get("channel_id")
        source_channel_id = _non_empty_string(
            channel_value, f"observations[{index}].source_channel_id"
        )
        text = raw.get("text")
        if not isinstance(text, str):
            raise GoldContractError(f"observations[{index}].text must be a string")

        ordinal = raw.get("source_ordinal")
        if ordinal is not None and (isinstance(ordinal, bool) or not isinstance(ordinal, int)):
            raise GoldContractError(f"observations[{index}].source_ordinal must be an integer")

        return cls(
            observation_id=observation_id,
            source_provenance_id=source_provenance_id,
            source_channel_id=source_channel_id,
            text=text,
            source_kind=_optional_string(raw.get("source_kind"), f"observations[{index}].source_kind"),
            source_room_id=_optional_string(raw.get("source_room_id"), f"observations[{index}].source_room_id"),
            source_file_id=_optional_string(raw.get("source_file_id"), f"observations[{index}].source_file_id"),
            source_ordinal=ordinal,
        )


@dataclass(frozen=True, slots=True)
class EvidenceGroup:
    """One required AND-group with OR alternatives."""

    group_id: str
    alternatives: tuple[str, ...]

    @classmethod
    def from_mapping(cls, raw: Mapping[str, Any], index: int = 0) -> "EvidenceGroup":
        raw = _mapping(raw, f"required_evidence_groups[{index}]")
        group_id = _non_empty_string(raw.get("group_id"), f"required_evidence_groups[{index}].group_id")
        alternatives_value = raw.get("alternatives")
        if alternatives_value is None:
            # ``observation_ids`` is accepted as a descriptive alias for
            # callers that do not want to use the word "alternative" for a
            # single-evidence group.  The normalized contract is still OR.
            alternatives_value = raw.get("observation_ids")
        alternatives = _string_list(
            alternatives_value,
            f"required_evidence_groups[{index}].alternatives",
            allow_empty=False,
        )
        return cls(group_id=group_id, alternatives=alternatives)


_UNREVIEWED_STATUSES = frozenset({"unreviewed", "synthetic", "pending"})
_REVIEWED_STATUSES = frozenset({"reviewed", "approved", "human_reviewed"})


def _normalize_review_status(value: Any, field: str) -> str:
    value = _non_empty_string(value, field).lower()
    if value in _UNREVIEWED_STATUSES:
        return "unreviewed"
    if value in _REVIEWED_STATUSES:
        return "reviewed"
    raise GoldContractError(
        f"{field} must be one of unreviewed, reviewed, or approved"
    )


@dataclass(frozen=True, slots=True)
class GoldQuestion:
    question_id: str
    split: str
    question_split_group: str
    episode_group: str
    allowed_source_channel_ids: tuple[str, ...]
    required_evidence_groups: tuple[EvidenceGroup, ...]
    forbidden_observation_ids: tuple[str, ...]
    abstain_expected: bool
    review_status: str
    reviewer: str | None
    prompt: str | None = None

    @property
    def positive(self) -> bool:
        return bool(self.required_evidence_groups)

    @classmethod
    def from_mapping(cls, raw: Mapping[str, Any], index: int = 0) -> "GoldQuestion":
        raw = _mapping(raw, f"questions[{index}]")
        prefix = f"questions[{index}]"
        question_id = _non_empty_string(raw.get("question_id"), f"{prefix}.question_id")
        split = _non_empty_string(raw.get("split"), f"{prefix}.split")

        # Keep both names explicit in the normalized model.  The aliases make
        # migration from early evaluation manifests safe without inferring a
        # group from a person's name or source text.
        split_group_value = raw.get("question_split_group")
        if split_group_value is None:
            split_group_value = raw.get("split_group")
        if split_group_value is None:
            split_group_value = raw.get("episode_group")
        question_split_group = _non_empty_string(
            split_group_value, f"{prefix}.question_split_group"
        )
        episode_group = _non_empty_string(
            raw.get("episode_group", question_split_group), f"{prefix}.episode_group"
        )

        allowed_channels = _string_list(
            raw.get("allowed_source_channel_ids"),
            f"{prefix}.allowed_source_channel_ids",
            allow_empty=True,
        )

        groups_value = raw.get("required_evidence_groups")
        if isinstance(groups_value, (str, bytes, bytearray)) or not isinstance(groups_value, Sequence):
            raise GoldContractError(f"{prefix}.required_evidence_groups must be a list")
        groups = tuple(
            EvidenceGroup.from_mapping(item, group_index)
            for group_index, item in enumerate(groups_value)
        )
        group_ids = [group.group_id for group in groups]
        if len(group_ids) != len(set(group_ids)):
            raise DuplicateIdentifierError(f"{prefix}.required_evidence_groups has duplicate group IDs")

        forbidden = _string_list(
            raw.get("forbidden_observation_ids", []),
            f"{prefix}.forbidden_observation_ids",
        )
        abstain_expected = raw.get("abstain_expected", False)
        if not isinstance(abstain_expected, bool):
            raise GoldContractError(f"{prefix}.abstain_expected must be a boolean")
        if abstain_expected and groups:
            raise GoldContractError(
                f"{prefix} cannot require evidence and expect abstention"
            )
        if not abstain_expected and not groups:
            raise EmptyPositiveGoldError(
                f"{prefix} has empty positive gold; set abstain_expected=true for an abstention case"
            )

        review_status = _normalize_review_status(
            raw.get("review_status"), f"{prefix}.review_status"
        )
        reviewer = _optional_string(raw.get("reviewer"), f"{prefix}.reviewer")
        if review_status == "reviewed" and reviewer is None:
            raise GoldContractError(f"{prefix}.reviewer is required for reviewed gold")
        if review_status == "unreviewed" and reviewer is not None:
            raise GoldContractError(f"{prefix}.reviewer must be null for unreviewed gold")

        prompt = raw.get("prompt", raw.get("question"))
        if prompt is not None and not isinstance(prompt, str):
            raise GoldContractError(f"{prefix}.prompt must be a string when present")

        return cls(
            question_id=question_id,
            split=split,
            question_split_group=question_split_group,
            episode_group=episode_group,
            allowed_source_channel_ids=allowed_channels,
            required_evidence_groups=groups,
            forbidden_observation_ids=forbidden,
            abstain_expected=abstain_expected,
            review_status=review_status,
            reviewer=reviewer,
            prompt=prompt,
        )


@dataclass(frozen=True, slots=True)
class GoldSet:
    schema_version: int
    dataset_id: str
    gold_kind: str
    review_status: str
    reviewer: str | None
    review_revision: str | None
    observations: Mapping[str, Observation]
    questions: tuple[GoldQuestion, ...]
    metadata: Mapping[str, Any]

    @classmethod
    def from_mapping(cls, raw: Mapping[str, Any]) -> "GoldSet":
        raw = _mapping(raw, "gold")
        schema_version = raw.get("schema_version")
        if schema_version != 1:
            raise GoldContractError("gold.schema_version must be 1")
        dataset_id = _non_empty_string(raw.get("dataset_id"), "gold.dataset_id")
        gold_kind = _non_empty_string(raw.get("gold_kind"), "gold.gold_kind").lower()
        if gold_kind not in {"synthetic", "human_reviewed"}:
            raise GoldContractError("gold.gold_kind must be synthetic or human_reviewed")
        review_status = _normalize_review_status(
            raw.get("review_status"), "gold.review_status"
        )
        reviewer = _optional_string(raw.get("reviewer"), "gold.reviewer")
        if review_status == "reviewed" and reviewer is None:
            raise GoldContractError("gold.reviewer is required for reviewed gold")
        if review_status == "unreviewed" and reviewer is not None:
            raise GoldContractError("gold.reviewer must be null for unreviewed gold")
        if gold_kind == "human_reviewed" and review_status != "reviewed":
            raise GoldContractError(
                "human_reviewed gold must have review_status=reviewed"
            )

        raw_observations = raw.get("observations")
        if isinstance(raw_observations, (str, bytes, bytearray)) or not isinstance(raw_observations, Sequence):
            raise GoldContractError("gold.observations must be a list")
        observations: dict[str, Observation] = {}
        provenance_ids: dict[str, str] = {}
        for index, item in enumerate(raw_observations):
            observation = Observation.from_mapping(item, index)
            if observation.observation_id in observations:
                raise DuplicateIdentifierError(
                    f"duplicate observation_id: {observation.observation_id}"
                )
            other_observation = provenance_ids.get(observation.source_provenance_id)
            if other_observation is not None:
                raise DuplicateIdentifierError(
                    "duplicate immutable source provenance ID "
                    f"{observation.source_provenance_id} for "
                    f"{other_observation} and {observation.observation_id}"
                )
            observations[observation.observation_id] = observation
            provenance_ids[observation.source_provenance_id] = observation.observation_id

        raw_questions = raw.get("questions", raw.get("gold_cases"))
        if isinstance(raw_questions, (str, bytes, bytearray)) or not isinstance(raw_questions, Sequence):
            raise GoldContractError("gold.questions must be a list")
        if not raw_questions:
            raise GoldContractError("gold.questions must not be empty")
        questions = tuple(
            GoldQuestion.from_mapping(item, index)
            for index, item in enumerate(raw_questions)
        )
        question_ids = [question.question_id for question in questions]
        if len(question_ids) != len(set(question_ids)):
            raise DuplicateIdentifierError("duplicate question_id")

        split_groups: dict[str, set[str]] = {}
        episode_groups: dict[str, set[str]] = {}
        for question in questions:
            split_groups.setdefault(question.question_split_group, set()).add(question.split)
            episode_groups.setdefault(question.episode_group, set()).add(question.split)
        _reject_split_leaks(split_groups, "question_split_group")
        _reject_split_leaks(episode_groups, "episode_group")

        known_ids = set(observations)
        for question in questions:
            positive_ids: list[str] = []
            for group in question.required_evidence_groups:
                for observation_id in group.alternatives:
                    _require_known_id(observation_id, known_ids, question.question_id)
                    positive_ids.append(observation_id)
                    observation = observations[observation_id]
                    if observation.source_channel_id not in question.allowed_source_channel_ids:
                        raise GoldContractError(
                            f"question {question.question_id} positive evidence "
                            f"{observation_id} is outside allowed source channels"
                        )
            if len(positive_ids) != len(set(positive_ids)):
                raise DuplicateIdentifierError(
                    f"question {question.question_id} reuses an observation across evidence groups"
                )
            for observation_id in question.forbidden_observation_ids:
                _require_known_id(observation_id, known_ids, question.question_id)
            if set(positive_ids) & set(question.forbidden_observation_ids):
                raise GoldContractError(
                    f"question {question.question_id} marks positive evidence as forbidden"
                )
            if question.positive and not question.allowed_source_channel_ids:
                raise GoldContractError(
                    f"question {question.question_id} needs an explicit allowed source channel"
                )

        metadata = {
            key: value
            for key, value in raw.items()
            if key not in {"observations", "questions", "gold_cases"}
        }
        return cls(
            schema_version=schema_version,
            dataset_id=dataset_id,
            gold_kind=gold_kind,
            review_status=review_status,
            reviewer=reviewer,
            review_revision=_optional_string(raw.get("review_revision"), "gold.review_revision"),
            observations=MappingProxyType(observations),
            questions=questions,
            metadata=MappingProxyType(metadata),
        )

    @property
    def qualification_eligible(self) -> bool:
        """Whether this gold may be used for a qualification decision.

        Synthetic or partially reviewed gold is useful for regression tests,
        but cannot mark a retriever qualified.
        """

        return (
            self.gold_kind == "human_reviewed"
            and self.review_status == "reviewed"
            and self.reviewer is not None
            and all(
                question.review_status == "reviewed" and question.reviewer is not None
                for question in self.questions
            )
        )

    @property
    def qualification_status(self) -> str:
        if self.qualification_eligible:
            return "eligible_human_reviewed"
        if self.gold_kind == "synthetic":
            return "ineligible_synthetic"
        return "ineligible_unreviewed"


def _reject_split_leaks(groups: Mapping[str, set[str]], field: str) -> None:
    for group_id, splits in groups.items():
        # A group is an episode boundary, not a question variant label.  Keep
        # all split partitions disjoint; in particular dev/holdout may never
        # share an episode.
        if len(splits) > 1:
            joined = ", ".join(sorted(splits))
            raise SplitLeakageError(
                f"{field} {group_id!r} crosses evaluation splits: {joined}"
            )


def _require_known_id(observation_id: str, known_ids: set[str], question_id: str) -> None:
    if observation_id not in known_ids:
        raise UnknownObservationReferenceError(
            f"question {question_id} references unknown observation_id {observation_id}"
        )


def load_gold(source: GoldSet | Mapping[str, Any] | str | Path) -> GoldSet:
    """Load and fully validate a gold mapping or JSON path."""

    if isinstance(source, GoldSet):
        return source
    if isinstance(source, (str, Path)):
        path = Path(source)
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise GoldContractError(f"unable to load gold JSON: {path}") from exc
        return GoldSet.from_mapping(raw)
    return GoldSet.from_mapping(source)


def validate_gold(source: GoldSet | Mapping[str, Any] | str | Path) -> GoldSet:
    """Explicit alias for :func:`load_gold` used by integration runners."""

    return load_gold(source)


def _deduplicate_retrieved_ids(
    values: Iterable[str], known_ids: set[str], question_id: str
) -> tuple[str, ...]:
    """Deduplicate independent observations while preserving first rank.

    Repeated IDs are expected when overlapping windows contain the same source
    observation.  Unknown IDs are an error so a broken adapter cannot silently
    turn into an apparent retrieval miss.
    """

    result: list[str] = []
    seen: set[str] = set()
    for index, observation_id in enumerate(values):
        if not isinstance(observation_id, str) or not observation_id.strip():
            raise GoldContractError(
                f"retrieved[{question_id}][{index}] must be a non-empty observation_id"
            )
        if observation_id not in known_ids:
            raise UnknownObservationReferenceError(
                f"retrieved question {question_id} references unknown observation_id {observation_id}"
            )
        if observation_id not in seen:
            seen.add(observation_id)
            result.append(observation_id)
    return tuple(result)


@dataclass(frozen=True, slots=True)
class QuestionEvaluation:
    question_id: str
    split: str
    positive: bool
    retrieved_observation_ids: tuple[str, ...]
    recovered_group_count: int
    required_group_count: int
    evidence_recall: float | None
    complete_group_recovery: bool | None
    forbidden_observation_ids: tuple[str, ...]
    forbidden_hit_count: int
    out_of_scope_observation_ids: tuple[str, ...]
    out_of_scope_hit_count: int
    abstain_expected: bool
    retrieval_empty: bool
    retrieval_empty_on_expected_abstain: bool | None

    def as_dict(self) -> dict[str, Any]:
        return {
            "question_id": self.question_id,
            "split": self.split,
            "positive": self.positive,
            "retrieved_observation_ids": list(self.retrieved_observation_ids),
            "recovered_group_count": self.recovered_group_count,
            "required_group_count": self.required_group_count,
            "evidence_recall": self.evidence_recall,
            "complete_group_recovery": self.complete_group_recovery,
            "forbidden_observation_ids": list(self.forbidden_observation_ids),
            "forbidden_hit_count": self.forbidden_hit_count,
            "out_of_scope_observation_ids": list(self.out_of_scope_observation_ids),
            "out_of_scope_hit_count": self.out_of_scope_hit_count,
            "abstain_expected": self.abstain_expected,
            "retrieval_empty": self.retrieval_empty,
            "retrieval_empty_on_expected_abstain": self.retrieval_empty_on_expected_abstain,
        }


@dataclass(frozen=True, slots=True)
class EvaluationReport:
    dataset_id: str
    k: int
    k_unit: str
    question_count: int
    positive_question_count: int
    required_group_count: int
    recovered_group_count: int
    evidence_recall: float | None
    complete_group_recovery_count: int
    complete_group_recovery_rate: float | None
    forbidden_hit_count: int
    forbidden_case_count: int
    forbidden_case_rate: float | None
    out_of_scope_hit_count: int
    out_of_scope_case_count: int
    out_of_scope_case_rate: float | None
    abstain_expected_count: int
    retrieval_empty_on_expected_abstain_count: int
    retrieval_empty_on_expected_abstain_rate: float | None
    positive_empty_retrieval_count: int
    qualification_eligible: bool
    qualification_status: str
    question_reports: tuple[QuestionEvaluation, ...]
    limitations: tuple[str, ...]

    @property
    def complete_group_recovery(self) -> float | None:
        """Convenience alias for the case-level complete recovery rate."""

        return self.complete_group_recovery_rate

    @property
    def forbidden_hits(self) -> int:
        return self.forbidden_hit_count

    @property
    def abstain_expected(self) -> int:
        return self.abstain_expected_count

    def as_dict(self) -> dict[str, Any]:
        return {
            "schema_version": 1,
            "dataset_id": self.dataset_id,
            "measurement_scope": "retrieval_only",
            "k": self.k,
            "k_unit": self.k_unit,
            "metrics": {
                "question_count": self.question_count,
                "positive_question_count": self.positive_question_count,
                "required_group_count": self.required_group_count,
                "recovered_group_count": self.recovered_group_count,
                "evidence_recall": self.evidence_recall,
                "complete_group_recovery_count": self.complete_group_recovery_count,
                "complete_group_recovery_rate": self.complete_group_recovery_rate,
                "forbidden_hit_count": self.forbidden_hit_count,
                "forbidden_case_count": self.forbidden_case_count,
                "forbidden_case_rate": self.forbidden_case_rate,
                "out_of_scope_hit_count": self.out_of_scope_hit_count,
                "out_of_scope_case_count": self.out_of_scope_case_count,
                "out_of_scope_case_rate": self.out_of_scope_case_rate,
                "abstain_expected_count": self.abstain_expected_count,
                "retrieval_empty_on_expected_abstain_count": self.retrieval_empty_on_expected_abstain_count,
                "retrieval_empty_on_expected_abstain_rate": self.retrieval_empty_on_expected_abstain_rate,
                "positive_empty_retrieval_count": self.positive_empty_retrieval_count,
            },
            "qualification": {
                "eligible": self.qualification_eligible,
                "status": self.qualification_status,
            },
            "questions": [question.as_dict() for question in self.question_reports],
            "limitations": list(self.limitations),
        }

    def to_dict(self) -> dict[str, Any]:
        return self.as_dict()

    def to_json(self, *, indent: int = 2) -> str:
        return json.dumps(self.as_dict(), ensure_ascii=False, indent=indent, sort_keys=True)


def _retrieved_mapping(
    gold: GoldSet, retrieved: Mapping[str, Iterable[str]] | Sequence[Iterable[str]]
) -> dict[str, Iterable[str]]:
    if isinstance(retrieved, Mapping):
        unknown_questions = set(retrieved) - {question.question_id for question in gold.questions}
        if unknown_questions:
            raise GoldContractError(
                "retrieved contains unknown question IDs: "
                + ", ".join(sorted(map(str, unknown_questions)))
            )
        missing_questions = [
            question.question_id
            for question in gold.questions
            if question.question_id not in retrieved
        ]
        if missing_questions:
            raise GoldContractError(
                "retrieved is missing question IDs: " + ", ".join(missing_questions)
            )
        return dict(retrieved)

    if isinstance(retrieved, (str, bytes, bytearray)) or not isinstance(retrieved, Sequence):
        raise GoldContractError(
            "retrieved must map question IDs to observation ID lists, or be an aligned list"
        )
    if len(retrieved) != len(gold.questions):
        raise GoldContractError(
            "aligned retrieved list must have one observation ID list per gold question"
        )
    return {
        question.question_id: values
        for question, values in zip(gold.questions, retrieved)
    }


def evaluate_retrieval(
    gold: GoldSet | Mapping[str, Any] | str | Path,
    retrieved: Mapping[str, Iterable[str]] | Sequence[Iterable[str]],
    *,
    k: int = 10,
) -> EvaluationReport:
    """Evaluate ranked observation IDs against validated gold.

    ``k`` is applied *after* duplicate observation IDs are collapsed.  This
    models overlapping windows without allowing one source observation to
    inflate rank or evidence recall.
    """

    if isinstance(k, bool) or not isinstance(k, int) or k <= 0:
        raise GoldContractError("k must be a positive integer")
    gold_set = load_gold(gold)
    retrieved_by_question = _retrieved_mapping(gold_set, retrieved)
    known_ids = set(gold_set.observations)

    reports: list[QuestionEvaluation] = []
    total_groups = 0
    recovered_groups = 0
    positive_questions = 0
    complete_cases = 0
    forbidden_hits = 0
    forbidden_cases = 0
    out_of_scope_hits = 0
    out_of_scope_cases = 0
    abstain_expected_count = 0
    retrieval_empty_on_expected_abstain_count = 0
    positive_empty_count = 0

    for question in gold_set.questions:
        unique_ids = _deduplicate_retrieved_ids(
            retrieved_by_question[question.question_id], known_ids, question.question_id
        )
        top_ids = unique_ids[:k]
        top_set = set(top_ids)
        hits_by_group = [
            bool(top_set & set(group.alternatives))
            for group in question.required_evidence_groups
        ]
        recovered = sum(hits_by_group)
        group_count = len(question.required_evidence_groups)
        evidence_recall = recovered / group_count if group_count else None
        complete = bool(group_count) and recovered == group_count
        if question.positive:
            positive_questions += 1
            total_groups += group_count
            recovered_groups += recovered
            if complete:
                complete_cases += 1
            if not top_ids:
                positive_empty_count += 1

        forbidden = tuple(
            observation_id
            for observation_id in top_ids
            if observation_id in set(question.forbidden_observation_ids)
        )
        forbidden_hit_count = len(forbidden)
        forbidden_hits += forbidden_hit_count
        if forbidden_hit_count:
            forbidden_cases += 1

        out_of_scope = tuple(
            observation_id
            for observation_id in top_ids
            if gold_set.observations[observation_id].source_channel_id
            not in question.allowed_source_channel_ids
        )
        out_scope_count = len(out_of_scope)
        out_of_scope_hits += out_scope_count
        if out_scope_count:
            out_of_scope_cases += 1

        retrieval_empty = not top_ids
        retrieval_empty_on_expected_abstain: bool | None
        if question.abstain_expected:
            abstain_expected_count += 1
            retrieval_empty_on_expected_abstain = retrieval_empty
            if retrieval_empty:
                retrieval_empty_on_expected_abstain_count += 1
        else:
            retrieval_empty_on_expected_abstain = None

        reports.append(
            QuestionEvaluation(
                question_id=question.question_id,
                split=question.split,
                positive=question.positive,
                retrieved_observation_ids=top_ids,
                recovered_group_count=recovered,
                required_group_count=group_count,
                evidence_recall=evidence_recall,
                complete_group_recovery=complete if question.positive else None,
                forbidden_observation_ids=forbidden,
                forbidden_hit_count=forbidden_hit_count,
                out_of_scope_observation_ids=out_of_scope,
                out_of_scope_hit_count=out_scope_count,
                abstain_expected=question.abstain_expected,
                retrieval_empty=retrieval_empty,
                retrieval_empty_on_expected_abstain=retrieval_empty_on_expected_abstain,
            )
        )

    return EvaluationReport(
        dataset_id=gold_set.dataset_id,
        k=k,
        k_unit="independent_observations",
        question_count=len(gold_set.questions),
        positive_question_count=positive_questions,
        required_group_count=total_groups,
        recovered_group_count=recovered_groups,
        evidence_recall=(recovered_groups / total_groups) if total_groups else None,
        complete_group_recovery_count=complete_cases,
        complete_group_recovery_rate=(complete_cases / positive_questions) if positive_questions else None,
        forbidden_hit_count=forbidden_hits,
        forbidden_case_count=forbidden_cases,
        forbidden_case_rate=(forbidden_cases / len(gold_set.questions)) if gold_set.questions else None,
        out_of_scope_hit_count=out_of_scope_hits,
        out_of_scope_case_count=out_of_scope_cases,
        out_of_scope_case_rate=(out_of_scope_cases / len(gold_set.questions)) if gold_set.questions else None,
        abstain_expected_count=abstain_expected_count,
        retrieval_empty_on_expected_abstain_count=retrieval_empty_on_expected_abstain_count,
        retrieval_empty_on_expected_abstain_rate=(
            retrieval_empty_on_expected_abstain_count / abstain_expected_count
            if abstain_expected_count else None
        ),
        positive_empty_retrieval_count=positive_empty_count,
        qualification_eligible=gold_set.qualification_eligible,
        qualification_status=gold_set.qualification_status,
        question_reports=tuple(reports),
        limitations=(
            "Retrieval evidence only; no generated-answer correctness judge is run.",
            "Speaker/person attribution correctness is not measured; only explicit observation IDs can score.",
            "Overlapping windows are deduplicated by observation_id, and window IDs are not accepted as evidence.",
            "An empty retrieval is a retrieval-empty diagnostic; it is not evidence that a generated answer should abstain or that abstention was correct.",
            "Synthetic or unreviewed gold is diagnostic and cannot mark qualification eligibility.",
        ),
    )


def evaluate(
    gold: GoldSet | Mapping[str, Any] | str | Path,
    retrieved: Mapping[str, Iterable[str]] | Sequence[Iterable[str]],
    *,
    k: int = 10,
) -> EvaluationReport:
    """Short alias for :func:`evaluate_retrieval`."""

    return evaluate_retrieval(gold, retrieved, k=k)


